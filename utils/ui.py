def setup(page_title: str | None = None):
    """Inject CSS; call at the top of every page."""
    st.markdown(CSS, unsafe_allow_html=True)


def hero(title, subtitle, extra=""):
    st.markdown(f'<div class="hero"><h1>{title}</h1><p>{subtitle}</p>{extra}</div>', unsafe_allow_html=True)


def kpi(col, label, value, sub=""):
    col.markdown(f'<div class="kpi"><div class="l">{label}</div><div class="v">{value}</div>'
                 f'<div class="s">{sub}</div></div>', unsafe_allow_html=True)


def card(col, title, body):
    col.markdown(f'<div class="card"><h4>{title}</h4><div>{body}</div></div>', unsafe_allow_html=True)


def disclaimer():
    st.markdown(f'<div class="disclaimer"><b>⚠️ Educational Disclaimer.</b> {DISCLAIMER}</div>', unsafe_allow_html=True)


def flow(steps):
    parts = []
    for i, (t, d) in enumerate(steps):
        parts.append(f'<div class="step"><b>{t}</b><br><span style="font-size:.85rem;opacity:.8">{d}</span></div>')
        if i < len(steps) - 1:
            parts.append('<div class="arrow">➜</div>')
    st.markdown(f'<div class="flow">{"".join(parts)}</div>', unsafe_allow_html=True)


def pdf_viewer(path: Path, height=720):
    data = path.read_bytes()
    b64 = base64.b64encode(data).decode()
    st.markdown(f'<iframe src="data:application/pdf;base64,{b64}" width="100%" height="{height}" '
                f'style="border:1px solid rgba(128,128,160,.3);border-radius:12px"></iframe>', unsafe_allow_html=True)


def param_sidebar(prefix="g", defaults=None, show_N=True):
    """Shared pricing-parameter widgets; state persists across pages via session_state keys."""
    d = dict(S0=100.0, K=100.0, r=5.0, sigma=20.0, T=0.25, N=100)
    if defaults:
        d.update(defaults)
    with st.sidebar:
        st.markdown("### ⚙️ Model inputs")
        S0 = st.number_input("Spot price S₀", 1.0, 10000.0, d["S0"], 1.0, key=f"{prefix}_S0")
        K = st.number_input("Strike K", 1.0, 10000.0, d["K"], 1.0, key=f"{prefix}_K")
        r = st.slider("Risk-free rate r (%)", 0.0, 15.0, d["r"], 0.25, key=f"{prefix}_r") / 100
        sg = st.slider("Volatility σ (%)", 1.0, 120.0, d["sigma"], 1.0, key=f"{prefix}_sg") / 100
        T = st.slider("Maturity T (years)", 0.05, 5.0, d["T"], 0.05, key=f"{prefix}_T")
        N = st.slider("Tree steps N", 3, 500, d["N"], 1, key=f"{prefix}_N") if show_N else d["N"]
    return S0, K, r, sg, T, N


